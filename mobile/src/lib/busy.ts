/**
 * Кога приетото `send` може да покаже „Genesis работи…“ преди допитването.
 *
 * Одит 2026-10-27: useGenesis слагаше busy = true с отговора на `send`. Но
 * сървърът пуска хода и вдига "user" ПРЕДИ да отговори на `send`, и бърз ход
 * (/todos, /plan, /help) свършва дотогава: допитването с busy = false идваше
 * първо, а отговорът на `send` след него връщаше busy = true — и то стоеше до
 * края на следващото дълго допитване (до 20 s, нищо не го буди): „■ Спри“
 * вместо „Изпрати“, „Genesis мисли…“ и скрити команди в менюто. Измерено срещу
 * истинския remote_server (tests/fake_genesis.py): /todos и /plan — 2 от 5
 * команди с последно допитване busy = false преди отговора на `send`.
 *
 * Сега: busy от `send` само ако междувременно не е дошло допитване — то вече
 * казва истинското състояние след изпращането.
 */
export class BusyAfterSend {
  private polls = 0;

  /** Отговор на `events` е приложен. */
  polled(): void {
    this.polls += 1;
  }

  /** Преди `send`: функцията казва, когато дойде отговорът, дали да се
   *  покаже busy (true — нито едно допитване не е дошло междувременно). */
  sending(): () => boolean {
    const at = this.polls;
    return () => this.polls === at;
  }
}
