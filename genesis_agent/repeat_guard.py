"""
genesis_agent.repeat_guard — спира хода, когато моделът върти един и същ
инструмент, без нищо да се променя.

Цикълът на инструментите брои рундове и спира на тавана (config.TOOL_ROUND_CAP).
Това ограничава ЦЕНАТА, но не разпознава ПРОВАЛА: модел, който вика
`USE_SKILL` със същата заявка рунд след рунд, изчерпва целия бюджет и
потребителят вижда "Достигнат таван от 25 инструмент-рунда" — най-скъпото
възможно съобщение, защото пристига последно и не носи нито резултат, нито
обяснение.

Таванът беше вдигнат от 8 на 25, за да не се реже истинска многостъпкова
работа по средата. Това е правилно за работа, която напредва, но направи
въртенето на място три пъти по-скъпо: измерено срещу този цикъл, един
повтарян извик изгаря всичките 25 рунда (преди — 8).

Какво се брои за въртене (нарочно тясно): ИДЕНТИЧЕН инструмент с ИДЕНТИЧНИ
аргументи, върнал ИДЕНТИЧЕН резултат, пореден път. Изходът е в ключа, защото
само той различава цикъл от напредък — `RUN_CMD: pytest` два пъти подред е
напълно нормално, ако вторият път изходът е различен (нещо е поправено
междувременно). Щом и входът, и изходът съвпадат буквално, рундът не е
донесъл нищо ново по дефиниция — това е заключение, не догадка, и затова
предпазителят няма нужда от списък "безопасни" инструменти, който би
трябвало да се поддържа при всеки нов tool.

Стъпаловидно нарочно: второто еднакво минава с бележка (моделът получава
шанс сам да смени подхода — често е достатъчно), третото спира хода. Нищо
не се потиска преди това и нито един извик не се блокира: предпазителят
наблюдава, не филтрира.
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass

# Второто еднакво повторение → бележка към модела. Третото → спираме хода.
WARN_AT = 2
STOP_AT = 3


@dataclass(frozen=True)
class Verdict:
    """Какво да прави цикълът след един изпълнен инструмент."""

    repeats: int
    """Колко пъти ПОДРЕД този извик върна същия резултат (1 = първи път)."""

    stop: bool
    """Ходът да спре — повече рундове не могат да донесат нищо ново."""

    note: str
    """Текст за модела; празен низ, когато няма какво да се каже."""


def _fingerprint(name: str, arguments: object, result: str) -> str:
    """Стабилен отпечатък на (инструмент, аргументи, резултат).

    Аргументите се канонизират с подредени ключове, за да не се броят два
    еднакви извика за различни само защото моделът е сериализирал JSON-а в
    друг ред. Резултатът влиза хешнат — пълните изходи (repo map, дълъг
    stdout) не бива да се трупат в паметта за целия ход.
    """
    try:
        canon = json.dumps(arguments, sort_keys=True, ensure_ascii=False, default=str)
    except (TypeError, ValueError):
        canon = repr(arguments)
    blob = f"{name}\x00{canon}\x00{result}".encode(errors="replace")
    return hashlib.sha256(blob).hexdigest()


class RepeatGuard:
    """Пази състоянието за ЕДИН ход. Нов ход → нов RepeatGuard."""

    def __init__(self, warn_at: int = WARN_AT, stop_at: int = STOP_AT) -> None:
        self.warn_at = warn_at
        self.stop_at = stop_at
        self._last: str = ""
        self._streak: int = 0

    def observe(self, name: str, arguments: object, result: str) -> Verdict:
        """Отчита един изпълнен инструмент и казва дали ходът да продължи.

        Поредицата се нулира при всеки извик, който се различава по нещо —
        друг инструмент, други аргументи или друг изход. Затова A, B, A не е
        въртене, а A, A, A е.
        """
        fp = _fingerprint(name, arguments, result)
        if fp == self._last:
            self._streak += 1
        else:
            self._last = fp
            self._streak = 1

        if self._streak >= self.stop_at:
            return Verdict(
                repeats=self._streak,
                stop=True,
                note=(
                    f"[Система]: `{name}` беше извикан {self._streak} пъти подред със същите "
                    "аргументи и върна буквално същия резултат. Този подход не води "
                    "доникъде — спирам хода, за да не изгоря останалите рундове."
                ),
            )
        if self._streak >= self.warn_at:
            return Verdict(
                repeats=self._streak,
                stop=False,
                note=(
                    f"[Система]: Това е {self._streak}-рото извикване на `{name}` със същите "
                    "аргументи и същия резултат. Повтарянето няма да даде друго — "
                    "или ползвай вече полученото, или смени подхода. Ако търсиш умение, "
                    "което не съществува, напиши кода сам."
                ),
            )
        return Verdict(repeats=self._streak, stop=False, note="")

    def observe_text_result(self, result: str) -> Verdict:
        """Същото, за текстовия таг-режим, където има само изходен низ.

        Там резултатът вече носи и кой инструмент е бил ("[RUN_CMD: ...]"),
        и какво е върнал, така че целият низ е достатъчен отпечатък.
        """
        name = result[1:result.index(":")].strip() if (
            result.startswith("[") and ":" in result[:40]
        ) else "инструментът"
        return self.observe(name, None, result)
