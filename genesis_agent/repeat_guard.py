"""
genesis_agent.repeat_guard — спира хода, когато моделът върти един и същ
инструмент, без нищо да се променя.

Цикълът на инструментите брои рундове и спира на тавана (config.TOOL_ROUND_CAP).
Това ограничава ЦЕНАТА, но не разпознава ПРОВАЛА: модел, който вика
`USE_SKILL` със същата заявка рунд след рунд, изчерпва целия бюджет и
потребителят вижда "Достигнат таван от 25 инструмент-рунда" — най-скъпото
възможно съобщение, защото пристига последно и не носи нито резултат, нито
обяснение.

Таванът беше вдигнат от 8 на 25, за да не се реже истинска многостъпкова
работа по средата. Това е правилно за работа, която напредва, но направи
въртенето на място три пъти по-скъпо: измерено срещу този цикъл, един
повтарян извик изгаря всичките 25 рунда (преди — 8).

Какво се брои за въртене (нарочно тясно): ИДЕНТИЧЕН инструмент с ИДЕНТИЧНИ
аргументи, върнал ИДЕНТИЧЕН резултат, пореден път. Изходът е в ключа, защото
само той различава цикъл от напредък — `RUN_CMD: pytest` два пъти подред е
напълно нормално, ако вторият път изходът е различен (нещо е поправено
междувременно). Щом и входът, и изходът съвпадат буквално, рундът не е
донесъл нищо ново по дефиниция — това е заключение, не догадка, и затова
предпазителят няма нужда от списък "безопасни" инструменти, който би
трябвало да се поддържа при всеки нов tool.

Стъпаловидно нарочно: второто еднакво минава с бележка (моделът получава
шанс сам да смени подхода — често е достатъчно), третото спира хода. Нищо
не се потиска преди това и нито един извик не се блокира: предпазителят
наблюдава, не филтрира.

Известен фалшиво-положителен случай, приет съзнателно: модел, който чака нещо
външно, като проверява едно и също ТРИ пъти подред (`ls build/`, докато тече
компилация) и получава един и същ изход, ще бъде спрян, макар четвъртият път
да би показал промяна. Затова и двете съобщения казват вместо това да чака в
самата команда (`sleep 5 && ...`) — така един рунд свършва работата на три.
Спирането не е фатално: казва причината и ходът продължава с ново съобщение.
"""
from __future__ import annotations

import hashlib
import json
import re
from collections import deque
from dataclasses import dataclass

# Второто еднакво повторение → бележка към модела. Третото → спираме хода.
WARN_AT = 2
STOP_AT = 3
# Колко последни извика се помнят за кръговете (A, B, A, B, A): 8 стигат за
# кръг от три инструмента, повторен до третото връщане (2·3 + 1 = 7).
CYCLE_WINDOW = 8


@dataclass(frozen=True)
class Verdict:
    """Какво да прави цикълът след един изпълнен инструмент."""

    repeats: int
    """Колко пъти ПОДРЕД този извик върна същия резултат (1 = първи път)."""

    stop: bool
    """Ходът да спре — повече рундове не могат да донесат нищо ново."""

    note: str
    """Текст за модела; празен низ, когато няма какво да се каже."""


def _fingerprint(name: str, arguments: object, result: str) -> str:
    """Стабилен отпечатък на (инструмент, аргументи, резултат).

    Аргументите се канонизират с подредени ключове, за да не се броят два
    еднакви извика за различни само защото моделът е сериализирал JSON-а в
    друг ред. Резултатът влиза хешнат — пълните изходи (repo map, дълъг
    stdout) не бива да се трупат в паметта за целия ход.
    """
    try:
        canon = json.dumps(arguments, sort_keys=True, ensure_ascii=False, default=str)
    except (TypeError, ValueError):
        canon = repr(arguments)
    blob = f"{name}\x00{canon}\x00{result}".encode(errors="replace")
    return hashlib.sha256(blob).hexdigest()


# Команда, която само чака (`sleep 10`, `sleep 5 && …`, `timeout /t 5`, `Start-Sleep`).
_SLEEP = re.compile(r"\s*(?:sleep|timeout\s+/t|start-sleep)\b", re.IGNORECASE)


def _waits(name: str, arguments: object, result: str) -> bool:
    """Чакане, при което времето е напредъкът: проверка на фонова задача, която
    още върви, или команда, която само спи (ревю 2026-10-11).

    Измерено: BG_OUTPUT (върви; нищо ново) ↔ RUN_CMD `sleep 10` дават буквално
    същите резултати всеки път — кръгът спираше хода на петия извик, докато
    `npm run build` си вървеше нормално."""
    head = result.split("\n", 1)[0]
    if name == "BG_OUTPUT":
        return "(върви;" in head
    if name == "RUN_CMD":
        command = arguments.get("command") if isinstance(arguments, dict) else None
        if not isinstance(command, str):   # таг-режим: командата е в заглавието
            command = head[len("[RUN_CMD:"):] if head.startswith("[RUN_CMD:") else ""
        return bool(_SLEEP.match(command))
    return False


class RepeatGuard:
    """Пази състоянието за ЕДИН ход. Нов ход → нов RepeatGuard."""

    def __init__(self, warn_at: int = WARN_AT, stop_at: int = STOP_AT) -> None:
        self.warn_at = warn_at
        self.stop_at = stop_at
        self._last: str = ""
        self._streak: int = 0
        self._recent: deque[tuple[str, str, bool]] = deque(maxlen=CYCLE_WINDOW)
        self._writes: int = 0   # успешни записи в таг-режим — белегът им в _recent

    def observe(self, name: str, arguments: object, result: str) -> Verdict:
        """Отчита един изпълнен инструмент и казва дали ходът да продължи.

        Поредицата се нулира при всеки извик, който се различава по нещо —
        друг инструмент, други аргументи или друг изход. Затова A, B, A не е
        въртене ПОДРЕД, а A, A, A е; кръговете без промяна (A, B, A, B, A)
        хваща `_cycle`.
        """
        fp = _fingerprint(name, arguments, result)
        if fp == self._last:
            self._streak += 1
        else:
            self._last = fp
            self._streak = 1
        self._recent.append((fp, name, _waits(name, arguments, result)))
        if self._streak < self.warn_at:
            cycle = self._cycle(fp)
            if cycle:
                return cycle

        if self._streak >= self.stop_at:
            return Verdict(
                repeats=self._streak,
                stop=True,
                note=(
                    f"[Система]: `{name}` беше извикан {self._streak} пъти подред със същите "
                    "аргументи и върна буквално същия резултат. Този подход не води "
                    "доникъде — спирам хода, за да не изгоря останалите рундове. "
                    "(Ако чакаш нещо външно да се промени, чакай В САМАТА команда — "
                    "напр. `sleep 5 && ...` — вместо да повтаряш проверката.)"
                ),
            )
        if self._streak >= self.warn_at:
            return Verdict(
                repeats=self._streak,
                stop=False,
                note=(
                    f"[Система]: Това е {self._streak}-рото извикване на `{name}` със същите "
                    "аргументи и същия резултат. Повтарянето няма да даде друго — "
                    "или ползвай вече полученото, или смени подхода. Ако търсиш умение, "
                    "което не съществува, напиши кода сам; ако чакаш нещо външно, "
                    "чакай в самата команда."
                ),
            )
        return Verdict(repeats=self._streak, stop=False, note="")

    def _cycle(self, fp: str) -> Verdict | None:
        """Кръг без промяна: A, B, A, B, A (bug fix, 2026-10-11).

        Поредицата по-горе вижда само ЕДНАКВИ извиквания ПОДРЕД. Измерено:
        READ_FILE app.py ↔ EDIT_FILE с липсващ anchor, всеки път същият
        резултат — изгаряше всичките 25 рунда, без предпазителят да каже нищо.
        Броим от първата поява на този отпечатък в прозореца: второ връщане с
        най-много още един инструмент между тях → бележка; трето, при което
        всичко в отрязъка се е повторило (нищо ново) → спираме. A, B, C с
        различни резултати не се повтарят и никога не спират. Кръг с чакане в
        него (`_waits`) не е кръг без промяна — между обиколките минава време.
        """
        fps = [f for f, _, _ in self._recent]
        start = fps.index(fp)
        segment = fps[start:]
        seen = segment.count(fp)
        if seen < 2 or any(w for _, _, w in list(self._recent)[start:]):
            return None
        names = [n for f, n, _ in self._recent if f in segment]
        loop = " ↔ ".join(dict.fromkeys(names))
        if seen >= self.stop_at and all(segment.count(f) >= 2 for f in segment):
            return Verdict(repeats=seen, stop=True, note=(
                f"[Система]: Кръг {loop} без промяна: същите извиквания върнаха "
                f"буквално същите резултати {seen} пъти. Този подход не води доникъде — "
                "спирам хода, за да не изгоря останалите рундове."))
        if len(set(segment)) <= 2:
            return Verdict(repeats=seen, stop=False, note=(
                f"[Система]: Въртиш се в кръг {loop}: същото извикване върна същия "
                "резултат като преди малко. Повтарянето няма да даде друго — ползвай "
                "полученото или смени подхода (напр. прочети файла и копирай точния текст)."))
        return None

    def observe_text_result(self, result: str) -> Verdict:
        """Същото, за текстовия таг-режим, където има само изходен низ.

        Там резултатът вече носи и кой инструмент е бил ("[RUN_CMD: ...]"),
        и какво е върнал, така че целият низ е достатъчен отпечатък.
        """
        name = result[1:result.index(":")].strip() if (
            result.startswith("[") and ":" in result[:40]
        ) else "инструментът"
        # Успешен запис казва само път и брой знаци — три различни версии на
        # файл с еднаква дължина изглеждаха като въртене и спираха хода
        # (2026-10-07). Тук съдържанието не се вижда; запис не е повторение.
        # Но е промяна — и нулира поредицата, както на native пътя, където
        # аргументите на всяка редакция са различни (одит 2026-10-22). Без това
        # RUN_CMD → EDIT ✓ → RUN_CMD → EDIT ✓ → RUN_CMD със същия червен изход
        # се броеше за „3 пъти подред“ и ходът спираше преди третата поправка.
        # Уникален белег в прозореца — и кръгът не се простира през записа.
        if name in ("WRITE_FILE", "EDIT_FILE") and "] ✓" in result.split("\n", 1)[0]:
            self._writes += 1
            self._last, self._streak = "", 0
            self._recent.append((f"write-{self._writes}", name, False))
            return Verdict(repeats=1, stop=False, note="")
        return self.observe(name, None, result)
