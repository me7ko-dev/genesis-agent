"""Скрит приемен тест: работни дни по чл. 154 КТ (ал. 2 в сила от 2017 г.).
Празници: 1.01, 3.03, 1.05, 6.05, 24.05, 6.09, 22.09, 24–26.12 и Велики петък
до Великденски понеделник (православен Великден). 1 ноември е неприсъствен
само за учебните заведения — за останалите е работен ден. Празник в
събота/неделя (без Великденските) → първият/първите два работни дни след него
са почивни; Великденските дни не се компенсират (ГИТ, 22.04.2024 — 7 май 2024
е работен)."""
from datetime import date

import pytest
from workdays import count_working_days, is_working_day

OFF = [
    date(2026, 1, 1), date(2026, 3, 3), date(2026, 5, 1), date(2026, 5, 6),
    date(2026, 9, 22), date(2026, 12, 24), date(2026, 12, 25),
    date(2026, 4, 10), date(2026, 4, 13),              # Великден 12.04.2026
    date(2025, 4, 18), date(2025, 4, 21),              # Великден 20.04.2025
    date(2029, 4, 6), date(2029, 4, 9),                # Великден 8.04.2029
    date(2030, 4, 26), date(2030, 4, 29),              # Великден 28.04.2030
    date(2026, 5, 25),                                 # 24.05 неделя
    date(2026, 9, 7),                                  # 6.09 неделя
    date(2026, 12, 28),                                # 26.12 събота
    date(2022, 1, 3), date(2023, 1, 2),                # 1.01 събота / неделя
    date(2021, 5, 3), date(2021, 5, 4),                # 1.05 събота + Великден 2.05
    date(2024, 5, 6),                                  # Гергьовден = Великденски понеделник
    date(2022, 12, 27), date(2022, 12, 28),            # 24–25.12 събота и неделя
    date(2027, 12, 27), date(2027, 12, 28),            # 25–26.12 събота и неделя
    date(2028, 12, 27),                                # 24.12 неделя
]

WORK = [
    date(2026, 3, 2), date(2026, 4, 14), date(2026, 9, 23), date(2026, 5, 26),
    date(2027, 11, 1),                                 # 1.11 понеделник — работен
    date(2026, 11, 2),                                 # 1.11 неделя — без компенсация
    date(2024, 5, 7),                                  # ГИТ: 6.05 не се компенсира
    date(2021, 5, 5), date(2022, 12, 29), date(2028, 12, 28), date(2022, 1, 4),
    date(2025, 4, 22), date(2026, 12, 29),
]


@pytest.mark.parametrize("d", OFF, ids=str)
def test_days_off(d):
    assert is_working_day(d) is False


@pytest.mark.parametrize("d", WORK, ids=str)
def test_working_days(d):
    assert is_working_day(d) is True


@pytest.mark.parametrize("d", [date(2026, 9, 26), date(2026, 9, 27)], ids=str)
def test_weekend(d):
    assert is_working_day(d) is False


@pytest.mark.parametrize("start,end,n", [
    (date(2026, 1, 1), date(2026, 12, 31), 249),
    (date(2022, 12, 1), date(2022, 12, 31), 19),
    (date(2021, 5, 1), date(2021, 5, 31), 17),
    (date(2024, 5, 1), date(2024, 5, 31), 19),
    (date(2026, 9, 21), date(2026, 9, 21), 1),       # един ден, включително
    (date(2026, 9, 22), date(2026, 9, 22), 0),
], ids=str)
def test_count(start, end, n):
    assert count_working_days(start, end) == n
